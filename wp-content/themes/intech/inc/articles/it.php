<li>почта, если она хранится у вас, а не у почтового сервиса;</li>
<li>базы данных сайтов и внутренних систем;</li>
<li>настройки сервера, роутера, программ — чтобы быстро восстановить работу на новом оборудовании;</li>
<li>записи видеонаблюдения, если их нужно хранить.</li>
</ul>

<h2>Готовая схема для небольшой компании</h2>
<ol>
<li><strong>Рабочие данные:</strong> сервер с базами 1С и общими папками.</li>
<li><strong>Первая копия:</strong> ежедневное (для 1С — несколько раз в день) копирование на сетевое хранилище (NAS) в офисе. Хранилище не подключено как сетевой диск к компьютерам сотрудников, копирование выполняется от отдельной учётной записи.</li>
<li><strong>Вторая копия:</strong> ежедневная или еженедельная отправка зашифрованной копии в облачное хранилище или в другое здание. Желательно — с защитой от удаления на заданный срок.</li>
<li><strong>Версии:</strong> ежедневные копии за последние недели, еженедельные — за несколько месяцев, ежемесячные — за год.</li>
<li><strong>Мониторинг:</strong> отчёт о каждом копировании приходит ответственному, ошибки не остаются незамеченными.</li>
<li><strong>Проверка:</strong> раз в месяц или квартал — тестовое восстановление.</li>
</ol>

<h2>Как часто копировать: RPO и RTO</h2>
<p>Специалисты используют два понятия, которые полезно обсудить с руководством:</p>
<ul>
<li><strong>RPO</strong> — сколько данных компания готова потерять. Если копия делается раз в сутки, в худшем случае пропадёт день работы.</li>
<li><strong>RTO</strong> — за какое время нужно восстановить работу. Восстановить базу из локального хранилища можно намного быстрее, чем скачивать большой объём из облака.</li>
</ul>
<p>Ответьте на вопрос: «Что будет, если бухгалтерия потеряет день работы? А неделю?» — и станет ясно, как часто нужны копии.</p>

<h2>Самое важное — проверка восстановления</h2>
<p>Резервная копия, из которой никто ни разу не восстанавливался, — это надежда, а не защита. Типичные сюрпризы при первой попытке восстановления:</p>
<ul>
<li>копирование перестало работать несколько месяцев назад, а уведомлений никто не получал;</li>
<li>в копию не попала база, которую добавили позже;</li>
<li>копия есть, но пароль от архива никто не помнит;</li>
<li>восстановление занимает в разы больше времени, чем ожидалось.</li>
</ul>
<p>Поэтому регулярно делайте тестовое восстановление: разверните базу 1С из копии в отдельную папку и убедитесь, что она открывается и в ней свежие данные. Результат проверки записывайте.</p>
