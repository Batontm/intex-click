<h2>Частые ошибки</h2>
<ul>
<li>копия лежит на том же диске или сервере, что и данные;</li>
<li>RAID-массив считают резервной копией;</li>
<li>сетевая папка с копиями постоянно подключена ко всем компьютерам;</li>
<li>синхронизацию с облаком принимают за резервное копирование;</li>
<li>копирование «настроили когда-то», и никто не проверяет, что оно до сих пор выполняется;</li>
<li>копируются файлы, но забыты базы данных, почта или настройки программ;</li>
<li>пароль от зашифрованных копий хранится только на сервере, который нужно восстанавливать.</li>
</ul>

