/* На посадочных своё описание — общее из header.php не выводим. */
function intech_is_landing() {
	return (bool) intech_current_landing();
}

/* ---------- Карта сайта (wp-sitemap.xml) ---------- */
add_action( 'init', function () {
	if ( ! function_exists( 'wp_register_sitemap_provider' ) || ! class_exists( 'WP_Sitemaps_Provider' ) ) {
		return;
	}
	if ( ! class_exists( 'Intech_Landings_Sitemap' ) ) {
		class Intech_Landings_Sitemap extends WP_Sitemaps_Provider {
			public function __construct() {
				$this->name        = 'services';
				$this->object_type = 'services';
			}
			public function get_url_list( $page_num, $object_subtype = '' ) {
				$list = array();
				foreach ( array_keys( intech_landings() ) as $slug ) {
					$list[] = array( 'loc' => intech_landing_url( $slug ) );
				}
				if ( function_exists( 'intech_pages' ) ) {
					foreach ( array_keys( intech_pages() ) as $p ) {
						$list[] = array( 'loc' => intech_page_url( $p ) );
					}
				}
				return $list;
			}
			public function get_max_num_pages( $object_subtype = '' ) {
				return 1;
			}
		}
	}
	wp_register_sitemap_provider( 'services', new Intech_Landings_Sitemap() );
}, 20 );
