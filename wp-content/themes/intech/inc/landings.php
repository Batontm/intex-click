/** Текущая посадочная страница или null. */
function intech_current_landing() {
	$slug = get_query_var( 'intech_landing' );
	$all  = intech_landings();
	return ( $slug && isset( $all[ $slug ] ) ) ? array_merge( array( 'slug' => $slug ), $all[ $slug ] ) : null;
}

/** Адрес посадочной страницы. */
function intech_landing_url( $slug ) {
	return home_url( '/' . $slug . '/' );
}

/* ---------- Адреса страниц ---------- */
add_action( 'init', function () {
	$slugs = implode( '|', array_map( 'preg_quote', array_keys( intech_landings() ) ) );
	add_rewrite_rule( '^(' . $slugs . ')/?$', 'index.php?intech_landing=$matches[1]', 'top' );
	// Обновляем правила один раз при изменении списка страниц.
	$ver = md5( $slugs );
	if ( get_option( 'intech_landings_rw' ) !== $ver ) {
		flush_rewrite_rules( false );
		update_option( 'intech_landings_rw', $ver );
	}
} );

add_filter( 'query_vars', function ( $vars ) {
	$vars[] = 'intech_landing';
	return $vars;
} );

/* Это обычная страница, а не главная и не 404. */
add_action( 'parse_query', function ( $q ) {
	if ( $q->is_main_query() && $q->get( 'intech_landing' ) ) {
		$q->is_home     = false;
		$q->is_404      = false;
		$q->is_page     = false;
		$q->is_singular = false;
	}
} );

add_filter( 'redirect_canonical', function ( $redirect ) {
	return get_query_var( 'intech_landing' ) ? false : $redirect;
} );

add_filter( 'template_include', function ( $template ) {
	if ( intech_current_landing() ) {
		status_header( 200 );
		$t = locate_template( 'template-landing.php' );
		if ( $t ) {
			return $t;
		}
	}
	return $template;
} );

/* ---------- SEO: title, description, canonical, микроразметка ---------- */
